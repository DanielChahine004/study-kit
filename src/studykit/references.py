r"""A writeup's references.bib, generated from report/references.txt, never typed.

A repository uses it through a two-line step3_outputs/references.py (`pixi run references`),
and studykit.testing checks it wherever report/references.txt exists. kit.toml may say
where the list, the cache and the bibliography are; the defaults are

    [references]
    list = "report/references.txt"
    cache = "report/references.json"
    bib = "<the writeup's folder>/references.bib"     # needed when kit.toml lists several writeups


    pixi run references              # render from the cache (offline)
    pixi run references --fetch      # fetch DOIs not yet in the cache, then render
    pixi run references --refresh    # refetch every DOI, then render

report/references.txt lists one reference per line: citation key, DOI, and
optional overrides as field=value for what the registry lacks or gets wrong
(year=1996, title="GPU-based ..."; quote values with spaces),
then an optional # note. Metadata comes from doi.org as CSL-JSON (Crossref for
journals, DataCite for arXiv and Zenodo), cached in report/references.json so
rendering is deterministic and works offline. A DOI that does not resolve
cannot enter the bibliography, so an invented reference fails here.

A reference with no DOI (an old journal issue, a book, a companion paper in
preparation) has "-" for its DOI, and its overrides are the whole entry, type=
included (type=book author="..." title="..." publisher="..." year=2004). Its
note says where it can be checked instead: a PMID, an ISBN. Give it url=...
(a PubMed or publisher page) so its reference links like the others; a book
or an unpublished paper may have none (NO_LINK_TYPES).

Each key starts with the first author's surname and holds the year, then
optionally a word (vanderlaan2010optical, Maas2009); case is ignored. It is
checked against the record, so a DOI that resolves to a different paper than
the one meant is caught offline. Where the record's first author is a
collaboration, the key may name the first person instead.

Rendering rules: more than MAX_AUTHORS authors print as the first KEEP_AUTHORS
and "others"; titles are double-braced so their case is kept; arXiv DOIs
(10.48550/arXiv.<id>) also carry eprint fields, and a misc entry gets a
howpublished line so plain styles print the arXiv id or software version.
"""
import html, json, pathlib, re, shlex, sys, unicodedata, urllib.request  # noqa: E401

from studykit import config

_CFG = config.load()
ROOT = _CFG["root"]
_REF = _CFG.get("references", {})
LIST = ROOT / _REF.get("list", "report/references.txt")
CACHE = ROOT / _REF.get("cache", "report/references.json")


def _bib():
    if "bib" in _REF:
        return ROOT / _REF["bib"]
    papers = sorted(_CFG["papers"])
    if len(papers) != 1:
        return None            # several writeups: kit.toml's [references] bib says which
    return ROOT / config.paper_dir(papers[0], _CFG) / "references.bib"


OUT = _bib()
# the writeup whose bibliography this is: the one whose folder holds OUT
PAPER = next((p for p in sorted(_CFG["papers"]) if OUT and OUT.parent == ROOT / config.paper_dir(p, _CFG)), None)
MAX_AUTHORS, KEEP_AUTHORS = 10, 3
HEADER = ("% Generated by step3_outputs/references.py from report/references.txt and the doi.org\n"
          "% metadata cached in report/references.json. Edit the list, never this file.\n")


CITE = re.compile(r"\\cite[a-zA-Z]*\*?(?:\[[^]]*\])*\{([^}]*)\}")   # \cite, \citep, \citealp, \citeauthor, ...


# entry types that may have neither a DOI nor a url, so their reference cannot link
NO_LINK_TYPES = {"book", "unpublished"}

# bibliography styles that drop the doi field, so the reference list would print no link
DROP_DOI = {"plain", "unsrt", "abbrv", "alpha"}

# entry types whose unsrtnat format prints the url field but not the doi
PRINT_NO_DOI = {"misc", "unpublished"}


def cited(tex):
    """The keys a LaTeX source cites, commented-out lines ignored."""
    tex = re.sub(r"(?<!\\)%.*", "", tex)
    keys = {k.strip() for group in CITE.findall(tex) for k in group.split(",") if k.strip()}
    # \claim{Key/id} prints \citep{Key} (step3_outputs/sources.py); \claim* prints nothing
    return keys | {c.strip().split("/")[0] for group in re.findall(r"\\claim\{([^}]*)\}", tex) for c in group.split(",") if c.strip()}


def entries():
    """[(key, doi or None, {override field: value})] in list order."""
    out = []
    for line in LIST.read_text().splitlines():
        line = line.split(" #", 1)[0].strip()
        if not line or line.startswith("#"):
            continue
        key, doi, *rest = shlex.split(line)
        out.append((key, None if doi == "-" else doi, dict(r.split("=", 1) for r in rest)))
    return out


def fetch(doi):
    req = urllib.request.Request(f"https://doi.org/{doi}", headers={
        "Accept": "application/vnd.citationstyles.csl+json", "User-Agent": "study-references/0.1"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


KEEP = ("type", "title", "container-title", "volume", "issue", "page", "article-number", "issued", "author", "version", "publisher", "DOI")


def slim(c):
    """The fields render_one reads, so the committed cache stays small and reviewable."""
    return {k: c[k] for k in KEEP if k in c}


def load_cache():
    return json.loads(CACHE.read_text()) if CACHE.exists() else {}


def tex(text):
    """Registry text as LaTeX: entities decoded, tags dropped, specials escaped."""
    text = re.sub(r"<sup>\s*TM\s*</sup>|[\u00ae\u2122]", "", html.unescape(str(text)))   # trademark marks
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"[\u2009\u202f]+", r"\\,", text)                         # thin spaces, as in "32 mm"
    text = re.sub(r"(?:\\,)?\s*\u00d7\s*(?:\\,)?", r" $\\times$ ", text)      # 32 mm x 32 mm
    text = text.replace("–", "--").replace("—", "---")
    return re.sub(r"(?<!\\)([&%#_])", r"\\\1", text)


def name(a):
    if a.get("literal") or a.get("name"):   # a collaboration or an unsplit name
        return "{" + tex(a.get("literal") or a["name"]) + "}"
    if a.get("given"):
        return f"{tex(a['family'])}, {tex(a['given'])}"
    return tex(a["family"])


def year(c):
    parts = (c.get("issued") or {}).get("date-parts") or [[None]]
    return parts[0][0]


def render_one(key, doi, over, c):
    if doi is None:                           # no DOI: the overrides are the whole entry
        over = dict(over)
        bibtype = over.pop("type", "misc")
        if not over.get("year"):
            sys.exit(f"{key}: an entry with no DOI needs year=... on its line in {LIST.name}")
        body = ",\n".join(f"  {f} = {{{{{v}}}}}" if f == "title" else f"  {f} = {{{v}}}" for f, v in over.items())
        return f"@{bibtype}{{{key},\n{body}\n}}\n"
    kind = c.get("type")
    arxiv = re.match(r"10\.48550/arxiv\.(.+)", doi, re.I)
    fields = {}
    if kind == "journal-article":
        bibtype, fields["journal"] = "article", tex(c.get("container-title", ""))
    elif kind in ("proceedings-article", "paper-conference"):
        bibtype, fields["booktitle"] = "inproceedings", tex(c.get("container-title", ""))
    else:
        bibtype = "misc"
    authors = c.get("author", [])
    names = [name(a) for a in authors]
    if len(names) > MAX_AUTHORS:
        names = names[:KEEP_AUTHORS] + ["others"]
    fields["author"] = " and ".join(names)
    fields["title"] = "{" + tex(c.get("title", "")) + "}"
    fields["year"] = year(c)
    for f, k in (("volume", "volume"), ("number", "issue"), ("pages", "page")):
        if c.get(k):
            fields[f] = tex(c[k]).replace("-", "--").replace("----", "--")
    if not fields.get("pages") and c.get("article-number"):
        fields["pages"] = tex(c["article-number"])
    if kind == "software":
        fields["version"] = tex(c.get("version", ""))
        fields["publisher"] = tex(c.get("publisher", ""))
    if arxiv:
        fields["eprint"] = arxiv.group(1)
        fields["archiveprefix"] = "arXiv"
        if bibtype == "misc":   # styles like unsrt print howpublished, not eprint
            fields["howpublished"] = f"arXiv:{arxiv.group(1)}"
    if kind == "software":
        fields["howpublished"] = f"{tex(c.get('publisher', ''))}, version {tex(c.get('version', ''))}"
    fields["doi"] = doi
    if bibtype in PRINT_NO_DOI:   # unsrtnat's misc prints a url but not a doi
        fields["url"] = f"https://doi.org/{doi}"
    fields.update({f: "{" + tex(v) + "}" if f == "title" else v for f, v in over.items()})
    if not fields.get("year"):
        sys.exit(f"{key}: {doi} has no year in its metadata; add year=... to its line in {LIST.name}")
    body = ",\n".join(f"  {f} = {{{v}}}" for f, v in fields.items() if v not in (None, ""))
    return f"@{bibtype}{{{key},\n{body}\n}}\n"


def plain(text):
    """Lower-case ASCII letters only: accents, braces, TeX accent commands and spaces dropped."""
    text = re.sub(r"\$?\\times\$?|\u00d7", "x", str(text))                    # 32 mm x 32 mm, either way
    text = re.sub(r"\\[a-zA-Z]+|\\.", "", text)
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z]", "", text.lower())


def surname(a):
    if a.get("literal") or a.get("name"):
        return (a.get("literal") or a["name"]).split()[0]
    if not a.get("given"):        # a whole name in one field, e.g. "Seth R. Johnson"
        return a.get("family", "").split()[-1]
    return a.get("family", "")


def first_surnames(c, over):
    """The surnames a key may start with: the first author's as rendered (an author override
    wins over the registry), and, where the record's first author is a collaboration, the first person's."""
    if "author" in over:
        first = over["author"].split(" and ")[0]
        return [first.split(",")[0] if "," in first else first.split()[-1]]
    authors = c.get("author") or [{}]
    out = [surname(authors[0])]
    if authors[0].get("literal") or authors[0].get("name"):
        out += [surname(a) for a in authors[1:] if a.get("family")][:1]
    return out


def first_surname(c, over):
    return first_surnames(c, over)[0]


def key_problem(key, doi, over, c):
    """Why a key does not match its record, or None. A key is surname + year + word, so a DOI
    that resolves to a different paper than the one meant fails here, offline."""
    prefix = plain(re.match(r"[^0-9]*", key).group())
    y = str(over.get("year") or year(c))
    ok = any(s and (prefix.startswith(s) or (s.startswith(prefix) and len(prefix) >= 3))
             for s in map(plain, first_surnames(c, over)))
    if not ok:
        return f"{key}: first author of {doi or 'the entry'} is {first_surname(c, over)!r}"
    if y not in key:
        return f"{key}: {doi or 'the entry'} is from {y}"
    return None


def override_problem(key, doi, over, c):
    """Why an override changes which work an entry names, or None.

    Overrides exist for the registry's gaps and its presentation: a missing year,
    lost accents, a lower-cased title, a collaboration in place of its first
    person. So an override may fill a field the record lacks, and may restyle
    one it has, but never replace it: the title keeps the record's letters, the
    authors are the record's people in order (a leading collaboration and a
    trailing "others" aside), and year, volume, issue and pages match where the
    record has them. Anything else is a different paper wearing this DOI.
    """
    if doi is None:
        return None
    if "title" in over and c.get("title") and plain(over["title"]) != plain(c["title"]):
        return f"{key}: title override is not the record's title restyled"
    if "author" in over and c.get("author"):
        mine = [n.strip() for n in over["author"].split(" and ")]
        mine = [plain(n.split(",")[0] if "," in n else n.split()[-1]) for n in mine if n != "others"]
        # a record with the names swapped between fields (family "Simon C", given "Blyth")
        # is still the same person, so a surname may match either field, in order
        people = [{plain(a["family"]), plain(a.get("given", ""))} for a in c["author"] if a.get("family")]
        if len(mine) > len(people) or any(m not in p for m, p in zip(mine, people)):
            return f"{key}: author override does not list the record's authors in order"
    first_page = lambda v: re.split(r"[^0-9A-Za-z]+", str(v).strip())[0]  # noqa: E731  "70" fills out to "70--83"
    for field, have, same in (("year", year(c), lambda a, b: str(a) == str(b)),
                              ("volume", c.get("volume"), lambda a, b: str(a) == str(b)),
                              ("number", c.get("issue"), lambda a, b: str(a) == str(b)),
                              ("pages", c.get("page") or c.get("article-number"), lambda a, b: first_page(a) == first_page(b))):
        if field in over and have and not same(over[field], have):
            return f"{key}: {field} override {over[field]!r} replaces the record's {have!r}"
    return None


def render():
    cache = load_cache()
    missing = [doi for _, doi, _ in entries() if doi and doi.lower() not in cache]
    if missing:
        sys.exit(f"not in {CACHE.name}: {missing}; run with --fetch")
    return HEADER + "\n" + "\n".join(render_one(k, d, o, cache[d.lower()] if d else {}) for k, d, o in entries())


def main():
    if OUT is None:
        sys.exit("kit.toml lists several writeups: say which bibliography in [references] bib = ...")
    cache = load_cache()
    refresh, fetch_new = "--refresh" in sys.argv, "--fetch" in sys.argv
    keys = [k for k, _, _ in entries()]
    dup = {k for k in keys if keys.count(k) > 1}
    if dup:
        sys.exit(f"duplicate keys in {LIST.name}: {sorted(dup)}")
    if refresh or fetch_new:
        for key, doi, _ in entries():
            if doi and (refresh or doi.lower() not in cache):
                cache[doi.lower()] = slim(fetch(doi))
                print("fetched", key, doi)
        CACHE.write_text(json.dumps(dict(sorted(cache.items())), indent=1, ensure_ascii=False) + "\n")
    OUT.write_text(render())
    print("wrote", OUT.relative_to(ROOT), f"({len(keys)} entries)")


if __name__ == "__main__":
    main()
